create table if not exists public.merch_store_categories (
  id bigint generated by default as identity primary key,
  parent_id bigint references public.merch_store_categories(id) on delete restrict,
  name text not null check (length(btrim(name)) > 0),
  slug text not null unique check (length(btrim(slug)) > 0),
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.merch_products
  add column if not exists category_id bigint
  references public.merch_store_categories(id) on delete set null;

create index if not exists merch_store_categories_parent_sort_idx
  on public.merch_store_categories(parent_id, sort_order, name);
create index if not exists merch_products_category_id_idx
  on public.merch_products(category_id);

alter table public.merch_store_categories enable row level security;
grant select on public.merch_store_categories to anon, authenticated;
grant insert, update, delete on public.merch_store_categories to authenticated;
grant usage, select on sequence public.merch_store_categories_id_seq to authenticated;

drop policy if exists "Public can view active merch store categories" on public.merch_store_categories;
create policy "Public can view active merch store categories"
  on public.merch_store_categories for select to anon, authenticated
  using (is_active = true);

drop policy if exists "FSB admins manage merch store categories" on public.merch_store_categories;
create policy "FSB admins manage merch store categories"
  on public.merch_store_categories for all to authenticated
  using (exists (
    select 1 from public.fsb_store_admins a
    where a.user_id = (select auth.uid())
      and lower(a.email) = lower(coalesce((select auth.jwt() ->> 'email'), ''))
  ))
  with check (exists (
    select 1 from public.fsb_store_admins a
    where a.user_id = (select auth.uid())
      and lower(a.email) = lower(coalesce((select auth.jwt() ->> 'email'), ''))
  ));

